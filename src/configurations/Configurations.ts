import type { CentiaHttpClient } from '../http/client';
import type { LocationResponse } from '../provisioning/types';

/** A Vidi configuration. */
export interface Configuration {
  /** Server generated identifier (`configuration_<name>_<id>`). Never changes, not even on rename. */
  key: string;
  name: string;
  description: string;
  /** When true the configuration can be read without a token. */
  published: boolean;
  /**
   * The Vidi configuration as JSON **text** — a string, not an object.
   * Must parse to a JSON object or array. Stored and returned unchanged.
   */
  body: string;
}

/** Body for creating a configuration. All four fields are required; `key` is generated by the server. */
export interface CreateConfigurationRequest {
  /** Non-empty name. */
  name: string;
  /** May be an empty string. */
  description: string;
  published: boolean;
  /** JSON text that parses to an object or array, e.g. `JSON.stringify(config)`. */
  body: string;
}

/** Partial update of a configuration: any non-empty subset of the four fields. */
export type PatchConfigurationRequest = Partial<CreateConfigurationRequest>;

/** Result of creating configurations: the Location header and the server generated keys parsed from it. */
export interface CreateConfigurationResponse extends LocationResponse {
  /** Keys of the created configurations, in request order. */
  keys: string[];
}

const BASE = 'api/v4/configurations';

function keyPath(key: string | string[]): string {
  // Dashboard-made keys can contain '@', '+' and '-'; encode each key on its
  // own ('+' must travel as %2B) and keep the list separator a literal comma.
  return (Array.isArray(key) ? key : [key]).map(encodeURIComponent).join(',');
}

function publicPath(database: string, key?: string, suffix = ''): string {
  const base = `${BASE}/database/${encodeURIComponent(database)}`;
  return key != null ? `${base}/${encodeURIComponent(key)}${suffix}` : base;
}

/**
 * Client for Vidi configurations (`/api/v4/configurations`).
 *
 * Management methods require a token from the database owner (sub-users get
 * `403 SUPER_USER_ONLY`). The `getPublicConfiguration*` methods read published
 * configurations anonymously and never send a token.
 *
 * ```ts
 * const configurations = new Configurations(createCentiaClient({ baseUrl, auth }));
 * const { keys } = await configurations.postConfiguration({
 *   name: 'My map', description: '', published: true, body: JSON.stringify({ brandName: 'My map' }),
 * });
 * const config = await configurations.getPublicConfigurationBody('mydb', keys[0]);
 * ```
 */
export class Configurations {
  constructor(private readonly client: CentiaHttpClient) {}

  /** List all configurations, published or not. */
  async getConfiguration(): Promise<Configuration[]>;
  /** Get one configuration. Unknown key: `404 CONFIGURATION_NOT_FOUND`. */
  async getConfiguration(key: string): Promise<Configuration>;
  /** Get several configurations. Any unknown key: `404 CONFIGURATION_NOT_FOUND`. */
  async getConfiguration(keys: string[]): Promise<Configuration[]>;
  async getConfiguration(key?: string | string[]): Promise<Configuration | Configuration[]> {
    if (Array.isArray(key) && key.length === 0) return [];
    const result = await this.client.request<Configuration | Configuration[]>({
      path: key != null ? `${BASE}/${keyPath(key)}` : BASE,
      method: 'GET',
    });
    // The API answers a single object for a one-key list; keep the array contract.
    return Array.isArray(key) && !Array.isArray(result) ? [result] : result;
  }

  /** Create one or more configurations. The keys are generated by the server. */
  async postConfiguration(
    body: CreateConfigurationRequest | CreateConfigurationRequest[],
  ): Promise<CreateConfigurationResponse> {
    const res = await this.client.requestFull({
      path: BASE,
      method: 'POST',
      body,
      expectedStatus: 201,
    });
    const location = res.getHeader('Location') ?? '';
    const last = location.split('?')[0].split('/').pop() ?? '';
    const keys = last.split(',').filter(Boolean).map(decodeURIComponent);
    return { location, keys };
  }

  /** Update any subset of name, description, published and body of one configuration. The key never changes. */
  async patchConfiguration(key: string, body: PatchConfigurationRequest): Promise<LocationResponse> {
    const res = await this.client.requestFull({
      path: `${BASE}/${keyPath(key)}`,
      method: 'PATCH',
      body,
      expectedStatus: 303,
    });
    return { location: res.getHeader('Location') ?? '' };
  }

  /** Delete one or more configurations. If any key is unknown, nothing is deleted (`404`). */
  async deleteConfiguration(key: string | string[]): Promise<void> {
    if (Array.isArray(key) && key.length === 0) return;
    await this.client.request({
      path: `${BASE}/${keyPath(key)}`,
      method: 'DELETE',
      expectedStatus: 204,
    });
  }

  /** List the published configurations of a database. No token needed. */
  async getPublicConfiguration(database: string): Promise<Configuration[]>;
  /**
   * Get one published configuration. No token needed. Unpublished and unknown
   * keys both answer `404 CONFIGURATION_NOT_FOUND`; unknown database `404 DATABASE_NOT_FOUND`.
   */
  async getPublicConfiguration(database: string, key: string): Promise<Configuration>;
  async getPublicConfiguration(database: string, key?: string): Promise<Configuration | Configuration[]> {
    return this.client.request<Configuration | Configuration[]>({
      path: publicPath(database, key),
      method: 'GET',
      contentType: null,
      anonymous: true,
    });
  }

  /**
   * Get the body of a published configuration, parsed — the `.json` form Vidi
   * loads. No token needed.
   */
  async getPublicConfigurationBody<T = unknown>(database: string, key: string): Promise<T> {
    return this.client.request<T>({
      path: publicPath(database, key, '.json'),
      method: 'GET',
      contentType: null,
      anonymous: true,
    });
  }

  /** URL of the raw `.json` body of a published configuration, e.g. to hand to Vidi. Makes no request. */
  publicConfigurationUrl(database: string, key: string): string {
    return `${this.client.baseUrl}/${publicPath(database, key, '.json')}`;
  }
}
